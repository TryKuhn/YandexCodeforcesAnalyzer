"""Test groups and points: the plan, the FreeMarker script built from it, the
scoring table for the statement and the group/points setup on Polygon.

Scoring scheme (what the user asked for): every group is ``COMPLETE_GROUP``
with ``ICPC`` feedback (first failed test stops the group), and all of the
group's points sit on ONE test of the group (the others carry 0) -- Polygon
sums test points, so the group is worth its points only when every test passes.
The samples group (manual tests 1..k, also shown in the statement) is worth 0
and gets ``COMPLETE`` feedback.

The script is generated by code, not by a model: sample tests are manual tests
1..k, script tests follow in plan order (``> $`` takes the next free index), and
each line ends with a globally unique number, so lines never repeat and every
group occupies a contiguous range of indices.
"""
from __future__ import annotations

import math
import re
from dataclasses import dataclass, field

MAX_TESTS = 300
MAX_CASE_COUNT = 100
NAME_RE = re.compile(r"^[A-Za-z0-9_-]{1,32}$")
GENERATOR_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,40}$")
ARGS_RE = re.compile(r"^[A-Za-z0-9_.,:=+\-/ ]*$")

POINTS_POLICY = "COMPLETE_GROUP"
FEEDBACK_GROUP = "ICPC"
FEEDBACK_SAMPLES = "COMPLETE"


class PlanError(ValueError):
    """The plan is inconsistent; the message is shown to the user."""


@dataclass
class Case:
    args: str
    count: int


@dataclass
class GroupPlan:
    name: str
    points: float = 0
    description: str = ""
    dependencies: list[str] = field(default_factory=list)
    generator: str | None = None
    cases: list[Case] = field(default_factory=list)
    samples: bool = False

    @property
    def test_count(self) -> int:
        return sum(c.count for c in self.cases)

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "points": self.points,
            "description": self.description,
            "dependencies": list(self.dependencies),
            "generator": self.generator,
            "cases": [{"args": c.args, "count": c.count} for c in self.cases],
            "samples": self.samples,
        }


@dataclass
class TestPlan:
    use_groups: bool
    groups: list[GroupPlan]
    note: str = ""

    @property
    def total_points(self) -> float:
        return sum(g.points for g in self.groups)

    @property
    def samples_group(self) -> GroupPlan | None:
        return next((g for g in self.groups if g.samples), None)

    @property
    def generated_groups(self) -> list[GroupPlan]:
        return [g for g in self.groups if not g.samples]

    def to_dict(self) -> dict:
        return {"use_groups": self.use_groups, "groups": [g.to_dict() for g in self.groups], "note": self.note}


def _points(value: object) -> float:
    try:
        points = float(value)  # type: ignore[arg-type]
    except (TypeError, ValueError, OverflowError):
        raise PlanError(f"баллы должны быть числом, получено {value!r}")
    if not math.isfinite(points):
        raise PlanError(f"баллы должны быть конечным числом, получено {value!r}")
    if points < 0:
        raise PlanError("баллы не могут быть отрицательными")
    return int(points) if points == int(points) else points


def normalize_plan(raw: dict) -> TestPlan:
    """Validate a plan from the user or a model; raise :class:`PlanError` with a readable reason."""
    if not isinstance(raw, dict):
        raise PlanError("план должен быть объектом")
    raw_groups = raw.get("groups")
    if not isinstance(raw_groups, list) or not raw_groups:
        raise PlanError("в плане нет групп")
    use_groups = bool(raw.get("use_groups", True))

    groups: list[GroupPlan] = []
    seen: set[str] = set()
    for i, rg in enumerate(raw_groups):
        if not isinstance(rg, dict):
            raise PlanError(f"группа №{i + 1}: ожидается объект")
        name = str(rg.get("name", "")).strip() or (str(i) if use_groups else "main")
        if not NAME_RE.match(name):
            raise PlanError(f"группа {name!r}: имя -- латиница, цифры, _ или -, до 32 символов")
        if name in seen:
            raise PlanError(f"группа {name!r} указана дважды")
        samples = bool(rg.get("samples", False))
        deps = [str(d).strip() for d in (rg.get("dependencies") or []) if str(d).strip()]
        for dep in deps:
            if dep not in seen:
                raise PlanError(f"группа {name}: зависимость {dep!r} должна быть группой выше по списку")
        group = GroupPlan(
            name=name,
            points=_points(rg.get("points", 0)),
            description=str(rg.get("description") or "").strip(),
            dependencies=list(dict.fromkeys(deps)),
            samples=samples,
        )
        if samples:
            if group.points:
                raise PlanError(f"группа примеров {name} должна стоить 0 баллов")
        else:
            generator = str(rg.get("generator") or f"gen_{name}").strip()
            if not GENERATOR_RE.match(generator):
                raise PlanError(f"группа {name}: недопустимое имя генератора {generator!r}")
            group.generator = generator
            for case in rg.get("cases") or []:
                if not isinstance(case, dict):
                    raise PlanError(f"группа {name}: случай теста должен быть объектом")
                args = " ".join(str(case.get("args", "")).split())
                if not ARGS_RE.match(args):
                    raise PlanError(f"группа {name}: недопустимые символы в аргументах {args!r}")
                try:
                    count = int(case.get("count", 1))
                except (TypeError, ValueError):
                    raise PlanError(f"группа {name}: count должен быть целым")
                if not 1 <= count <= MAX_CASE_COUNT:
                    raise PlanError(f"группа {name}: count от 1 до {MAX_CASE_COUNT}")
                group.cases.append(Case(args, count))
            if not group.cases:
                raise PlanError(f"группа {name}: нет ни одного теста (cases)")
        seen.add(name)
        groups.append(group)

    if sum(1 for g in groups if g.samples) > 1:
        raise PlanError("группа примеров может быть только одна")
    if not any(not g.samples for g in groups):
        raise PlanError("кроме группы примеров нужна хотя бы одна группа с генерируемыми тестами")
    if not use_groups:
        if len([g for g in groups if not g.samples]) != 1:
            raise PlanError("без групп план должен состоять из одного набора тестов")
        for g in groups:
            g.points = 0
            g.dependencies = []
    total = sum(g.test_count for g in groups)
    if total > MAX_TESTS:
        raise PlanError(f"слишком много тестов: {total} (максимум {MAX_TESTS})")
    return TestPlan(use_groups=use_groups, groups=groups, note=str(raw.get("note") or ""))


# --------------------------------------------------------------------------- script
@dataclass
class ScriptLine:
    group: str
    generator: str
    command: str  # without "> $"


def expand_lines(plan: TestPlan) -> list[ScriptLine]:
    """Every generated test in script order, with its unique final argument."""
    lines: list[ScriptLine] = []
    seed = 0
    for group in plan.generated_groups:
        assert group.generator
        for case in group.cases:
            for _ in range(case.count):
                seed += 1
                parts = [group.generator, case.args, str(seed)]
                lines.append(ScriptLine(group.name, group.generator, " ".join(p for p in parts if p)))
    return lines


def build_script(plan: TestPlan) -> str:
    """The FreeMarker script: one ``<#list>`` per case, unique numbers across the script."""
    out = ["<#-- Generated from the test plan by AI authoring. Edit the plan, not this script. -->"]
    seed = 0
    for group in plan.generated_groups:
        title = f"group {group.name}" if plan.use_groups else "tests"
        # inside a FreeMarker comment: no "-->" / "${" that would end it or be evaluated
        description = " ".join(re.sub(r"[^A-Za-z0-9 _.,:;=+*/()\[\]]", " ", group.description).split())[:80]
        out.append(f"<#-- {title}: {description} -->" if description else f"<#-- {title} -->")
        for case in group.cases:
            args = f" {case.args}" if case.args else ""
            if case.count == 1:
                out.append(f"{group.generator}{args} {seed + 1} > $")
            else:
                out.append(f"<#list 1..{case.count} as i>")
                out.append(f"{group.generator}{args} ${{i + {seed}}} > $")
                out.append("</#list>")
            seed += case.count
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- statement
def _latex_cell(text: str) -> str:
    """Escape what breaks a tabular cell, outside of $...$ math."""
    parts = re.split(r"(\$[^$]*\$)", text)
    return "".join(p if p.startswith("$") else re.sub(r"(?<!\\)([&%#])", r"\\\1", p) for p in parts)


def scoring_section(plan: TestPlan) -> str:
    """The «Система оценки» section: a table of groups, points and dependencies."""
    if not plan.use_groups:
        return ""
    rows = [
        "\\begin{center}",
        "\\begin{tabular}{|c|c|p{7cm}|c|}",
        "\\hline",
        "\\textbf{Группа} & \\textbf{Баллы} & \\textbf{Дополнительные ограничения} & "
        "\\textbf{Необходимые группы} \\\\",
        "\\hline",
    ]
    for g in plan.groups:
        description = _latex_cell(g.description or ("тесты из условия" if g.samples else "---"))
        deps = ", ".join(g.dependencies) or "---"
        rows.append(f"{g.name} & {g.points:g} & {description} & {deps} \\\\")
        rows.append("\\hline")
    rows += ["\\end{tabular}", "\\end{center}", ""]
    rows.append(
        "Баллы за группу начисляются, только если пройдены все тесты этой группы и все тесты "
        "необходимых для неё групп."
    )
    return "\n".join(rows)


# --------------------------------------------------------------------------- assignment
@dataclass
class Assignment:
    """Desired state of the testset after the plan is applied."""

    groups: dict[str, list[int]]          # group -> test indices
    points: dict[int, float]              # test index -> points
    policies: dict[str, tuple[str, str, list[str]]]  # group -> (points policy, feedback, deps)
    warnings: list[str] = field(default_factory=list)


def assign(plan: TestPlan, tests: list[dict], lines: list[ScriptLine]) -> Assignment:
    """Map Polygon's tests (after the script was saved) to plan groups.

    Script tests are matched to ``lines`` in index order; manual tests shown in
    the statement go to the samples group; any other manual test joins the last
    group (and is reported).
    """
    tests = sorted(tests, key=lambda t: t["index"])
    generated = [t for t in tests if not t.get("manual")]
    manual = [t for t in tests if t.get("manual")]
    if len(generated) != len(lines):
        raise PlanError(
            f"после сохранения скрипта в Polygon {len(generated)} сгенерированных тестов, а в плане {len(lines)}"
        )

    warnings: list[str] = []
    groups: dict[str, list[int]] = {g.name: [] for g in plan.groups}
    samples = plan.samples_group
    last = plan.generated_groups[-1].name
    for t in manual:
        if t.get("useInStatements") and samples is not None:
            groups[samples.name].append(t["index"])
        else:
            groups[last].append(t["index"])
            if not t.get("useInStatements"):
                warnings.append(f"ручной тест {t['index']} отнесён к группе {last}")
            else:
                warnings.append(f"тест-пример {t['index']} отнесён к группе {last} (в плане нет группы примеров)")
    for t, line in zip(generated, lines, strict=False):
        groups[line.group].append(t["index"])

    points: dict[int, float] = {}
    for g in plan.groups:
        indices = sorted(groups[g.name])
        groups[g.name] = indices
        if not indices:
            if g.samples:
                warnings.append(f"в группе примеров {g.name} нет тестов")
                continue
            raise PlanError(f"в группе {g.name} не оказалось тестов")
        for index in indices:
            points[index] = 0
        # all of the group's points on one test: the last one of the group
        points[indices[-1]] = g.points

    # a group with no tests does not exist on Polygon: nobody may depend on it
    empty = {g.name for g in plan.groups if not groups[g.name]}
    policies = {}
    for g in plan.groups:
        deps = [d for d in g.dependencies if d not in empty]
        if len(deps) != len(g.dependencies):
            dropped = sorted(set(g.dependencies) & empty)
            warnings.append(f"группа {g.name}: убрана зависимость от пустой группы {dropped}")
        policies[g.name] = (POINTS_POLICY, FEEDBACK_SAMPLES if g.samples else FEEDBACK_GROUP, deps)
    return Assignment(groups=groups, points=points, policies=policies, warnings=warnings)


def plan_from_snapshot(snapshot: dict) -> dict | None:
    """Reconstruct a draft plan from Polygon's current groups (for the editor)."""
    tests = snapshot.get("tests") or []
    by_group: dict[str, list[dict]] = {}
    for t in tests:
        if t.get("group") is not None:
            by_group.setdefault(str(t["group"]), []).append(t)
    if not by_group:
        return None
    policies = {g.get("name"): g for g in snapshot.get("groups") or []}
    groups = []
    for name, rows in sorted(by_group.items(), key=lambda kv: min(t["index"] for t in kv[1])):
        is_samples = all(t.get("useInStatements") for t in rows)
        groups.append({
            "name": name,
            "points": sum(float(t.get("points") or 0) for t in rows),
            "description": "тесты из условия" if is_samples else "",
            "dependencies": list((policies.get(name) or {}).get("dependencies") or []),
            "samples": is_samples,
            "generator": None if is_samples else f"gen_{name}",
            "cases": [] if is_samples else [{"args": "", "count": len(rows)}],
        })
    return {"use_groups": True, "groups": groups}
